#!/usr/bin/env python3
"""Generate the per-mode shortcut skills (skills/rapih-in-<mode>/) from one template.

    python tools/shortcuts.py          # write/refresh the shortcut folders
    python tools/shortcuts.py --check  # exit 1 if any shortcut differs from the template

Each shortcut is a thin, manual-only entry point so hosts list one slash command per mode
(/rapih-in-audit, $rapih-in-audit, /skill:rapih-in-audit, ...). It carries no rules of its own:
it loads the main rapih-in skill and runs it in that mode. Automatic matching stays with the
main skill only (disable-model-invocation for Claude Code, Cursor, Kimi; openai.yaml policy for Codex).
"""

import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKILLS = os.path.join(REPO, "skills")

MODES = {
    "audit": ("Find structure and responsibility problems; read-only.",
              "[path] [--exclude <path-or-glob>]..."),
    "plan": ("Target structure, file/symbol map, batches, and checks; read-only.",
             "[path] [--exclude <path-or-glob>]... [--only <ID,...>]"),
    "fix": ("Apply a still-valid plan in checkpointed batches, then validate.",
            "[path] [--dry-run] [--exclude <path-or-glob>]... [--only <ID,...>]"),
    "check": ("Verify references and affected behavior; read-only.",
              "[path] [--exclude <path-or-glob>]... [--only <ID,...>]"),
    "place": ("Recommend where a new file, feature, or extracted part belongs; read-only.",
              "<need>"),
    "all": ("Fresh audit, then plan, fix, and check with a checkpoint per batch.",
            "[path] [--dry-run] [--exclude <path-or-glob>]... [--only <ID,...>]"),
    "resume": ("Continue an unfinished rapih-in run with its original selection.",
               "[--dry-run]"),
}

SKILL_TEMPLATE = """---
name: rapih-in-{mode}
description: "Shortcut for rapih-in {mode}. {summary} Run only when the user invokes this command explicitly."
disable-model-invocation: true
argument-hint: "{hint}"
---

<!-- generated by tools/shortcuts.py; edit the template there -->

# rapih-in {mode}

Explicit shortcut. It adds no rules of its own.

1. Load the main skill: read `../rapih-in/SKILL.md`, relative to this file's folder (the `rapih-in` folder installed next to this one). If it is not there, load the skill named `rapih-in` through the host. If neither works, say that the main rapih-in skill is not installed and stop.
2. Follow the main skill exactly as if the user had typed `rapih-in {mode}` followed by the arguments they gave with this command. Mode, option, and mutation rules come only from the main skill.
"""

OPENAI_TEMPLATE = """interface:
  display_name: "rapih-in {mode}"
  short_description: "Shortcut for rapih-in {mode}"
  brand_color: "#038982"
policy:
  allow_implicit_invocation: false
"""


def expected():
    files = {}
    for mode, (summary, hint) in MODES.items():
        base = os.path.join(SKILLS, "rapih-in-" + mode)
        files[os.path.join(base, "SKILL.md")] = SKILL_TEMPLATE.format(mode=mode, summary=summary, hint=hint)
        files[os.path.join(base, "agents", "openai.yaml")] = OPENAI_TEMPLATE.format(mode=mode)
    return files


def main():
    check = "--check" in sys.argv[1:]
    bad = []
    for path, text in expected().items():
        try:
            with open(path, encoding="utf-8") as f:
                current = f.read()
        except FileNotFoundError:
            current = None
        if current == text:
            continue
        if check:
            bad.append(os.path.relpath(path, REPO))
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("wrote", os.path.relpath(path, REPO))
    if check:
        extra = [d for d in os.listdir(SKILLS) if d.startswith("rapih-in-") and d[9:] not in MODES]
        bad += ["unexpected shortcut folder skills/%s" % d for d in extra]
        print("\n".join(bad) if bad else "shortcuts match the template")
        return 1 if bad else 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
